"use strict"

const fs = require("node:fs")
const os = require("node:os")
const path = require("node:path")

const APP_NAME = "Salary Management"
const APPLICATION_ID = "salary-management"

const DOCKER_PATHS = {
  darwin: [
    "/usr/local/bin",
    "/opt/homebrew/bin",
    "/Applications/Docker.app/Contents/Resources/bin",
  ],
  linux: ["/usr/local/bin", "/usr/bin", "/snap/bin"],
  win32: ["C:\\Program Files\\Docker\\Docker\\resources\\bin"],
}

const ELECTRON_BINARY = {
  darwin: ["node_modules", "electron", "dist", "Electron.app", "Contents", "MacOS", "Electron"],
  win32: ["node_modules", "electron", "dist", "electron.exe"],
  linux: ["node_modules", "electron", "dist", "electron"],
}

function joinFor(platform, ...parts) {
  return platform === "win32" ? path.win32.join(...parts) : path.posix.join(...parts)
}

function posixQuote(value) {
  return `"${String(value).replace(/"/g, '\\"')}"`
}

function projectDesktopDir(projectRoot, platform) {
  return joinFor(platform, projectRoot, "desktop")
}

function electronBinary(projectRoot, platform) {
  const segments = ELECTRON_BINARY[platform]
  if (!segments) {
    throw new Error(`Платформа "${platform}" не підтримується.`)
  }

  return joinFor(platform, projectRoot, "desktop", ...segments)
}

function launcherPaths(platform, homeDir) {
  switch (platform) {
    case "darwin":
      return [path.join(homeDir, "Desktop", `${APP_NAME}.command`)]
    case "win32":
      return [path.join(homeDir, "Desktop", `${APP_NAME}.cmd`)]
    case "linux":
      return [
        path.join(homeDir, ".local", "share", "applications", `${APPLICATION_ID}.desktop`),
        path.join(homeDir, "Desktop", `${APP_NAME}.desktop`),
      ]
    default:
      throw new Error(`Платформа "${platform}" не підтримується.`)
  }
}

function darwinLauncher({ projectRoot, electronBinary: binary }) {
  const desktopDir = projectDesktopDir(projectRoot, "darwin")
  const dockerPath = DOCKER_PATHS.darwin.join(":")

  return [
    "#!/bin/zsh",
    `# Generated by "npm run shortcut" (${APP_NAME}).`,
    `export PATH="${dockerPath}:$PATH"`,
    `cd ${posixQuote(desktopDir)} || exit 1`,
    `exec ${posixQuote(binary)} .`,
    "",
  ].join("\n")
}

function win32Launcher({ projectRoot, electronBinary: binary }) {
  const desktopDir = projectDesktopDir(projectRoot, "win32")
  const dockerPath = DOCKER_PATHS.win32.join(";")

  return [
    "@echo off",
    "setlocal",
    `set "PATH=${dockerPath};%PATH%"`,
    `cd /d "${desktopDir}"`,
    `start "" "${binary}" .`,
    "endlocal",
    "",
  ].join("\r\n")
}

function linuxLauncher({ projectRoot, electronBinary: binary }) {
  const desktopDir = projectDesktopDir(projectRoot, "linux")
  const dockerPath = DOCKER_PATHS.linux.join(":")

  return [
    "[Desktop Entry]",
    "Type=Application",
    "Version=1.0",
    `Name=${APP_NAME}`,
    "Comment=Launch the Salary Management desktop app",
    `Exec=env PATH=${dockerPath} ${posixQuote(binary)} .`,
    `Path=${desktopDir}`,
    "Terminal=false",
    "Categories=Office;",
    "StartupNotify=true",
    "",
  ].join("\n")
}

function buildLaunchers({ platform, homeDir, projectRoot, electronBinary: binary }) {
  if (!ELECTRON_BINARY[platform]) {
    throw new Error(`Платформа "${platform}" не підтримується.`)
  }

  const paths = launcherPaths(platform, homeDir)
  const options = { projectRoot, electronBinary: binary }

  switch (platform) {
    case "darwin":
      return [{ path: paths[0], content: darwinLauncher(options), mode: 0o755 }]
    case "win32":
      return [{ path: paths[0], content: win32Launcher(options), mode: 0o644 }]
    case "linux": {
      const files = [{ path: paths[0], content: linuxLauncher(options), mode: 0o755 }]

      if (fs.existsSync(path.join(homeDir, "Desktop"))) {
        files.push({ path: paths[1], content: linuxLauncher(options), mode: 0o755 })
      }

      return files
    }
    default:
      return []
  }
}

function installShortcut({
  platform = process.platform,
  homeDir = os.homedir(),
  projectRoot = path.resolve(__dirname, "..", ".."),
  electronBinary: binary,
  log = console.log,
} = {}) {
  const binaryPath = binary || electronBinary(projectRoot, platform)

  if (!binary && !fs.existsSync(binaryPath)) {
    throw new Error(
      `Не знайдено Electron за шляхом: ${binaryPath}\n` +
        "Спочатку виконай: cd desktop && npm install"
    )
  }

  const files = buildLaunchers({
    platform,
    homeDir,
    projectRoot,
    electronBinary: binaryPath,
  })

  for (const file of files) {
    fs.mkdirSync(path.dirname(file.path), { recursive: true })
    fs.writeFileSync(file.path, file.content, { mode: file.mode })
    fs.chmodSync(file.path, file.mode)
    log(`Створено ярлик: ${file.path}`)
  }

  return files.map((file) => file.path)
}

function uninstallShortcut({
  platform = process.platform,
  homeDir = os.homedir(),
  log = console.log,
} = {}) {
  const removed = launcherPaths(platform, homeDir).filter((filePath) => fs.existsSync(filePath))

  for (const filePath of removed) {
    fs.rmSync(filePath, { force: true })
    log(`Видалено ярлик: ${filePath}`)
  }

  return removed
}

if (require.main === module) {
  const args = process.argv.slice(2)
  const remove = args.includes("--remove") || args.includes("--uninstall")

  try {
    if (remove) {
      const removed = uninstallShortcut()
      if (removed.length === 0) console.log("Ярликів не знайдено.")
    } else {
      const created = installShortcut()
      console.log(`\nГотово. Ярликів створено: ${created.length}.`)
      console.log("Тепер запускай застосунок подвійним кліком на Робочому столі.")
    }
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}

module.exports = {
  buildLaunchers,
  electronBinary,
  installShortcut,
  launcherPaths,
  uninstallShortcut,
}
